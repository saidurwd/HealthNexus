<?php

namespace App\Support;

use Illuminate\Support\Facades\Event;
use Illuminate\Support\Facades\File;

/** Reads the code and reports what is (and is not) covered by config/modules.php (guideline 8.2). */
class RegistryInspector
{
    /** Tables owned by the framework/platform rather than a module. */
    private const PLATFORM_TABLES = ['cache', 'cache_locks', 'jobs', 'job_batches', 'failed_jobs', 'sessions', 'password_reset_tokens', 'migrations', 'personal_access_tokens', 'permissions', 'roles', 'model_has_permissions', 'model_has_roles', 'role_has_permissions', 'users', 'user', 'organizations', 'user_organizations', 'hospitals', 'branches', 'user_branches', 'departments', 'organization_modules', 'settings', 'audit_logs', 'activity_logs', 'login_histories', 'break_glass_accesses', 'files', 'file_versions', 'notifications', 'workflow', 'workflows', 'states', 'countries', 'currencies', 'genders', 'marital_statuses', 'identification_types', 'specialties', 'security', 'two_factor', 'hospital_holidays'];

    /** @return array<string, list<string>> permission name => [] grouped list */
    public function permissions(): array
    {
        $names = [];
        $source = File::get(base_path('database/seeders/PermissionSeeder.php'));
        preg_match_all("/'([a-z_]+(?:\\.[a-z_]+){1,3})'/", $source, $m);
        foreach (array_unique($m[1]) as $name) {
            $names[$name] = explode('.', $name)[0];
        }
        ksort($names);

        return $names;
    }

    public function tables(): array
    {
        // Read from migration files, not the live database: it must give the same answer on every machine.
        return collect(File::files(database_path('migrations')))
            ->flatMap(function ($file) {
                preg_match_all("/Schema::create\\('([a-z0-9_]+)'/", File::get($file->getPathname()), $m);

                return $m[1];
            })
            ->unique()->sort()->values()->all();
    }

    public function ownerOfPermissionPrefix(string $prefix): ?string
    {
        foreach (config('modules') as $key => $module) {
            if (in_array($prefix, $module['permissions'], true)) {
                return $key;
            }
        }

        return null;
    }

    public function ownerOfTable(string $table): ?string
    {
        if (in_array($table, self::PLATFORM_TABLES, true)) {
            return 'core';
        }

        foreach (config('modules') as $key => $module) {
            foreach ($module['tables'] as $prefix) {
                if ($table === $prefix || str_starts_with($table, $prefix.'_')) {
                    return $key;
                }
            }
        }

        return null;
    }

    /** @return list<string> */
    public function problems(): array
    {
        $problems = [];

        foreach ($this->permissions() as $name => $prefix) {
            if ($this->ownerOfPermissionPrefix($prefix) === null) {
                $problems[] = "Permission [$name]: prefix [$prefix] is not registered in config/modules.php";
            }
        }

        foreach ($this->tables() as $table) {
            if ($this->ownerOfTable($table) === null) {
                $problems[] = "Table [$table] does not match any module table prefix in config/modules.php";
            }
        }

        return $problems;
    }

    public function modulesMarkdown(): string
    {
        $rows = collect(config('modules'))->map(fn ($m, $key) => sprintf(
            '| %s | %d | %s | %s | %s | %s | %s | %s |',
            $key, $m['phase'], $m['name'], $m['built'] ? 'built' : 'planned', $m['always_on'] ? 'always on' : 'switchable',
            implode(', ', $m['depends_on']) ?: '—', implode(', ', $m['permissions']), implode(', ', $m['tables']) ?: '—',
        ))->implode("\n");

        return "# Module Registry\n\n_Generated by `php artisan registry:export` from config/modules.php. Edit the config, not this file._\n\n"
            ."| Key | Phase | Module | Status | Enablement | Depends on | Permission prefixes | Table prefixes |\n|---|---|---|---|---|---|---|---|\n{$rows}\n";
    }

    /** Module Charter skeleton (guideline 7.4) for one module, with everything the code can answer already filled in. */
    public function charterMarkdown(string $key): string
    {
        $m = config("modules.$key");
        $tables = collect($this->tables())->filter(fn ($t) => $this->ownerOfTable($t) === $key)->values();
        $permissions = collect($this->permissions())->filter(fn ($prefix, $name) => in_array($prefix, $m['permissions'], true))->keys();
        $depends = $m['depends_on'] ? implode(', ', $m['depends_on']) : '—';

        return "# {$m['name']} — Module Charter\n\n"
            ."_Skeleton generated by `php artisan registry:export`; the lines marked **TODO** need the module owner. Do not delete this file: update it in every slice (guideline 7.4)._\n\n"
            ."- Phase / owner: {$m['phase']} / **TODO owner**\n"
            .'- Status: '.($m['built'] ? 'built' : 'planned').' · '.($m['always_on'] ? 'always on' : 'switchable per organization / hospital')."\n"
            ."- Purpose (2 lines): **TODO**\n"
            ."- Depends on (modules): $depends\n"
            .'- Permission prefixes: '.implode(', ', $m['permissions'])." ({$permissions->count()} permissions, see docs/registry/permissions.md)\n"
            .'- Table prefixes: '.(implode(', ', $m['tables']) ?: '—')." ({$tables->count()} tables, see docs/registry/tables.md)\n"
            .'- API base: /api/v1/'.implode(', /api/v1/', $m['api'])."\n"
            ."- Owns (entities) / Does NOT own: **TODO**\n"
            ."- Events published / consumed: see docs/events.md — **TODO** consumers\n"
            ."- Public contracts (`Contracts/`): **TODO**\n"
            ."- Status machines: **TODO**\n"
            ."- Settings keys: **TODO**\n"
            ."- Reports / KPIs: **TODO**\n"
            ."- Known limitations & deferred items: **TODO** (see docs/decisions/)\n\n"
            ."## Tables\n\n".$tables->map(fn ($t) => "- `$t`")->implode("\n")."\n";
    }

    public function permissionsMarkdown(): string
    {
        $out = "# Permission Registry\n\n_Generated from database/seeders/PermissionSeeder.php. Convention: `module.resource.action` (D-06)._\n";
        $byModule = collect($this->permissions())->groupBy(fn ($prefix) => $this->ownerOfPermissionPrefix($prefix) ?? 'UNREGISTERED');

        foreach ($byModule->sortKeys() as $module => $names) {
            $out .= "\n## $module (".$names->count().")\n\n".$names->keys()->map(fn ($n) => "- `$n`")->implode("\n")."\n";
        }

        return $out;
    }

    public function tablesMarkdown(): string
    {
        $out = "# Table Registry\n\n_Generated from the Schema::create calls in database/migrations._\n";
        $byModule = collect($this->tables())->groupBy(fn ($t) => $this->ownerOfTable($t) ?? 'UNREGISTERED');

        foreach ($byModule->sortKeys() as $module => $tables) {
            $out .= "\n## $module (".$tables->count().")\n\n".$tables->map(fn ($t) => "- `$t`")->implode("\n")."\n";
        }

        return $out;
    }

    public function eventsMarkdown(): string
    {
        $events = collect(File::allFiles(app_path('Events')))
            ->map(fn ($f) => 'App\\Events\\'.str_replace(['/', '.php'], ['\\', ''], $f->getRelativePathname()))
            ->sort()->values();

        $rows = $events->map(function (string $event) {
            $listeners = collect(Event::getRawListeners()[$event] ?? [])
                ->map(fn ($l) => is_string($l) ? $l : (is_array($l) ? implode('@', array_map(fn ($p) => is_object($p) ? get_class($p) : $p, $l)) : 'closure'))
                ->implode('<br>');
            $params = [];
            if (class_exists($event) && ($c = (new \ReflectionClass($event))->getConstructor())) {
                $params = array_map(fn ($p) => ($p->getType() ? $p->getType().' ' : '').'$'.$p->getName(), $c->getParameters());
            }

            return sprintf('| `%s` | %s | %s |', class_basename($event), implode(', ', $params) ?: '—', $listeners ?: '—');
        })->implode("\n");

        return "# Domain Events\n\n_Generated by `php artisan registry:export` (producer = the module namespace in the class name). Payloads should carry ids, not models (guideline 7.3)._\n\n| Event | Payload | Listeners |\n|---|---|---|\n{$rows}\n";
    }
}
